/// The value-in-a-range controls.
pub trait RangeBase: Control + RangeBaseLink {
    /// `Value`.
    fn value(&self) -> f32 {
        self.range_base_core().value
    }

    /// Sets `Value` (clamped to the range), raising `ValueChanged` when it changes (source: code).
    fn set_value(&mut self, value: f32) {
        let core = self.range_base_core();
        let value = value.clamp(core.minimum.min(core.maximum), core.maximum.max(core.minimum));
        let old = core.value;
        if old != value {
            self.range_base_core_mut().value = value;
            let mut args = NumericValueChangedEventArgs::new(old, value, ChangeSource::Code);
            self.on_value_changed(&mut EventCx::new(&mut args).from_class(self.class_name()));
        }
    }

    /// `Minimum`.
    fn minimum(&self) -> f32 {
        self.range_base_core().minimum
    }

    /// `Maximum`.
    fn maximum(&self) -> f32 {
        self.range_base_core().maximum
    }

    level_overridable! { base_range_base_mut;
        /// Raises `ValueChanged`.
        fn on_value_changed(NumericValueChangedEventArgs) => "OnValueChanged";
        /// Raises `Scroll`.
        fn on_scroll(ScrollEventArgs) => "OnScroll";
    }

    level_accessors! {
        /// `ValueChanged`.
        fn value_changed(NumericValueChangedEventArgs) => "OnValueChanged";
        /// `Scroll`.
        fn scroll(ScrollEventArgs) => "OnScroll";
    }
}

/// `ComponentCore` as the base of a non-visual component (`#[kubuno(extends = Component)]`).
impl Lineage for ComponentCore {
    const CHAIN: &'static [&'static str] = &["Component"];
}

/// Makes a level's core an object of its level: the abstract base a class extending the level
/// delegates to (`self.base_mut().on_click(e)` reaches the level's root behaviour, WinForms'
/// `base.OnClick(e)` in a class derived from `Control`). A core raises its events itself, with
/// the level's name as its class.
macro_rules! core_object {
    ($core:ty, $name:literal, [$($level:ident / $as_ref:ident / $as_mut:ident / $link:ident / $base:ident / $base_mut:ident),*]) => {
        impl super::ComponentLink for $core {
            fn as_any(&self) -> &dyn std::any::Any {
                self
            }
            fn as_any_mut(&mut self) -> &mut dyn std::any::Any {
                self
            }
            fn as_component(&self) -> &dyn super::Component {
                self
            }
            fn as_component_mut(&mut self) -> &mut dyn super::Component {
                self
            }
            fn class_name(&self) -> &'static str {
                $name
            }
            fn class_chain(&self) -> &'static [&'static str] {
                <$core as Lineage>::CHAIN
            }
            fn base_component(&self) -> Option<&dyn super::Component> {
                None
            }
            fn base_component_mut(&mut self) -> Option<&mut dyn super::Component> {
                None
            }
            $(
                fn $as_ref(&self) -> Option<&dyn $level> {
                    Some(self)
                }
                fn $as_mut(&mut self) -> Option<&mut dyn $level> {
                    Some(self)
                }
            )*
        }
        impl super::Component for $core {}
        $(
            impl $link for $core {
                fn $base(&self) -> Option<&dyn $level> {
                    None
                }
                fn $base_mut(&mut self) -> Option<&mut dyn $level> {
                    None
                }
            }
            impl $level for $core {}
        )*
    };
}


