/// The state of `ScrollableControl` (WinForms: the base of every control that scrolls its
/// content — `Panel`, `ContainerControl`).
pub struct ScrollableControlCore {
    pub control: ControlCore,
    /// `AutoScroll`: scroll bars appear when the content outgrows the control.
    pub auto_scroll: bool,
    /// `AutoScrollPosition`, the scroll offset (x, y), in DIP.
    pub auto_scroll_position: (f32, f32),
    /// `AutoScrollMinSize`.
    pub auto_scroll_min_size: Size,
}

impl Default for ScrollableControlCore {
    fn default() -> Self {
        let mut control = ControlCore::default();
        control.styles = control.styles | ControlStyles::CONTAINER_CONTROL;
        Self { control, auto_scroll: false, auto_scroll_position: (0.0, 0.0), auto_scroll_min_size: Size::EMPTY }
    }
}

deref_to!(ScrollableControlCore => control: ControlCore);
plumbing!(HasScrollableControlCore, ScrollableControlCore, scrollable_control_core, scrollable_control_core_mut, ScrollableControlLink, ScrollableControl, base_scrollable_control, base_scrollable_control_mut);
lower!(ScrollableControlCore:
    HasControlCore::control_core / control_core_mut -> ControlCore = control;
    HasComponentCore::component_core / component_core_mut -> ComponentCore = control.component;
);
impl Lineage for ScrollableControlCore {
    const CHAIN: &'static [&'static str] = &["ScrollableControl", "Control", "Component"];
}

/// A control that scrolls its content (WinForms `ScrollableControl`).
pub trait ScrollableControl: Control + ScrollableControlLink {
    /// `AutoScroll`.
    fn auto_scroll(&self) -> bool {
        self.scrollable_control_core().auto_scroll
    }

    /// `AutoScrollPosition`.
    fn auto_scroll_position(&self) -> (f32, f32) {
        self.scrollable_control_core().auto_scroll_position
    }

    /// Scrolls to `(x, y)`, raising `Scroll` when it moved (source: code).
    fn set_auto_scroll_position(&mut self, x: f32, y: f32) {
        let old = std::mem::replace(&mut self.scrollable_control_core_mut().auto_scroll_position, (x, y));
        if old != (x, y) {
            let mut args = ScrollEventArgs { old: old.1, new: y, ..Default::default() };
            self.on_scroll(&mut EventCx::new(&mut args).from_class(self.class_name()));
        }
    }

    level_overridable! { base_scrollable_control_mut;
        /// Raises `Scroll` (WinForms `ScrollableControl.OnScroll`).
        fn on_scroll(ScrollEventArgs) => "OnScroll";
    }

    level_accessors! {
        /// `Scroll`.
        fn scroll(ScrollEventArgs) => "OnScroll";
    }
}

