use super::cx::EventCx;
use super::{ComponentCore, HasComponentCore, Lineage};
use crate::events::{
    ChangeSource, CheckedChangedEventArgs, EmptyEventArgs, Event, FormClosedEventArgs, FormClosingEventArgs, MouseEventArgs, NumericValueChangedEventArgs, ScrollEventArgs,
    SelectionChangedEventArgs, TextChangedEventArgs,
};
use crate::registry::LayoutKind;

/// Declares a level's hidden plumbing: `Has<Level>Core` (the core accessor) and `<Level>Link`
/// (the base object a class delegates to), both generated by `#[derive(Component)]`.
macro_rules! plumbing {
    ($has:ident, $core:ident, $get:ident, $get_mut:ident, $link:ident, $level:ident, $base:ident, $base_mut:ident) => {
        #[doc = concat!("Reaches the [`", stringify!($core), "`] (generated by `#[derive(Component)]`; the cores implement it).")]
        #[doc(hidden)]
        pub trait $has {
            fn $get(&self) -> &$core;
            fn $get_mut(&mut self) -> &mut $core;
        }

        impl $has for $core {
            fn $get(&self) -> &$core {
                self
            }
            fn $get_mut(&mut self) -> &mut $core {
                self
            }
        }

        #[doc = concat!("The base object a `", stringify!($level), "` class delegates to (generated by `#[derive(Component)]`).")]
        #[doc(hidden)]
        pub trait $link: $has {
            fn $base(&self) -> Option<&dyn $level>;
            fn $base_mut(&mut self) -> Option<&mut dyn $level>;
        }
    };
}

/// Implements a lower level's accessor for a core, through the embedded field path.
macro_rules! lower {
    ($core:ident: $($has:ident :: $get:ident / $get_mut:ident -> $target:ty = $($field:ident).+;)*) => {$(
        impl $has for $core {
            fn $get(&self) -> &$target {
                &self.$($field).+
            }
            fn $get_mut(&mut self) -> &mut $target {
                &mut self.$($field).+
            }
        }
    )*};
}

/// Deref from a core to the core it embeds.
macro_rules! deref_to {
    ($core:ident => $field:ident: $target:ty) => {
        impl Deref for $core {
            type Target = $target;
            fn deref(&self) -> &$target {
                &self.$field
            }
        }
        impl DerefMut for $core {
            fn deref_mut(&mut self) -> &mut $target {
                &mut self.$field
            }
        }
    };
}

/// Overridable level methods: delegate to the base object, else raise.
macro_rules! level_overridable {
    ($base_mut:ident; $($(#[$doc:meta])* fn $method:ident($args:ty) => $event:literal;)*) => {$(
        $(#[$doc])*
        fn $method(&mut self, e: &mut EventCx<'_, $args>) {
            if let Some(base) = self.$base_mut() {
                return base.$method(e);
            }
            e.raise(&*self, $event);
        }
    )*};
}

/// Event accessors of a level.
macro_rules! level_accessors {
    ($($(#[$doc:meta])* fn $name:ident($args:ty) => $event:literal;)*) => {$(
        $(#[$doc])*
        fn $name(&self) -> Event<$args> {
            self.component_core().events.event($event)
        }
    )*};
}

fn styles_without(mut s: ControlStyles, off: ControlStyles) -> ControlStyles {
    s.set(off, false);
    s
}

