impl TextBoxBaseCore {
    /// WinForms `TextBoxBase.IsInputKey`: the horizontal arrows, Home/End; Enter and the vertical
    /// arrows when multiline; Tab when `accepts_tab`. What the text classes' `is_input_key`
    /// answers.
    pub fn is_input_key(&self, key: Keys) -> bool {
        if key.mods.alt {
            return false;
        }
        match key.key.0 {
            vk::LEFT | vk::RIGHT | vk::HOME | vk::END => true,
            vk::UP | vk::DOWN | vk::ENTER => self.multiline,
            vk::TAB => self.accepts_tab && !key.mods.ctrl,
            _ => false,
        }
    }
}

