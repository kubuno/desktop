//! The levels between `Control` and the concrete classes: `ScrollableControl` →
//! `ContainerControl` → `UserControl` / `View`, and the family bases `ButtonBase`, `TextBoxBase`,
//! `ListControl`, `LabelBase`, `ContainerBase`, `RangeBase` (the design note's `ScrollBarBase`:
//! every value-in-a-range control). Each is a trait with default methods plus a core struct the
//! classes of that family embed (`ButtonBaseCore` derefs to [`ControlCore`], which derefs to the
//! WinForms property replica).

use std::ops::{Deref, DerefMut};

use kubuno_controls::host::vk;
use kubuno_controls::ContentAlignment;
